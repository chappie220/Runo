#!/usr/bin/env python3
"""Generate src/pinyin/data/ (the pinyin input method's built-in data).

Usage, from the repository root:

    git clone --depth 1 --branch v0.15.0 https://github.com/mozillazg/pinyin-data
    git clone --depth 1 --branch v0.19.0 https://github.com/mozillazg/phrase-pinyin-data
    python3 scripts/pinyin-data.py pinyin-data phrase-pinyin-data

Only pinyin-data's pinyin.txt (with its kHanyuPinlu.txt and
kMandarin_8105.txt for how common a character is) and phrase-pinyin-data's
pinyin.txt are read; never cc_cedict.txt, zdic*.txt or large_pinyin.txt.
The output is deterministic, so running it again gives the same bytes.

Output, src/pinyin/data/pinyin.txt.gz (UTF-8 text, gzip):

    # comments
    @chars
    <char><reading>[,<reading>...]   one per line, most common first;
    -                                a line "-" ends a commonness tier
    @phrases
    <phrase> <syllable> <syllable>...   best first

Readings are toneless, with ü as v (u after j, q, x, y).

Order of characters: tier (0: in both kHanyuPinlu, the 现代汉语频率词典
characters, and kMandarin_8105, the 通用规范汉字表; 1: the rest of the
通用规范汉字表; 2: the rest of kHanyuPinlu, mostly traditional forms; 3: the
rest), then how many phrases
use the character (more first), then code point. Order of phrases: the mean
of log(1 + phrases using the character) over its characters (higher first),
then data order. Neither source has frequencies; these are proxies taken
from the same data.
"""

import collections
import gzip
import io
import math
import os
import sys
import unicodedata

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "pinyin", "data")


def toneless(reading):
    s = unicodedata.normalize("NFD", reading.strip().lower())
    s = s.replace("ü", "v")
    s = "".join(c for c in s if not unicodedata.combining(c))
    if s[:1] in ("j", "q", "x", "y"):
        s = s.replace("v", "u")
    if not s or not all("a" <= c <= "z" for c in s):
        return None
    return s


def version(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("# version:"):
                return line.split(":", 1)[1].strip()
    sys.exit(f"no version line in {path}")


def code_chars(path):
    """Characters of a `U+XXXX: readings  # c` file, with their readings."""
    out = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            code, readings = line.split(":", 1)
            c = chr(int(code.strip()[2:], 16))
            out[c] = [r for r in readings.strip().split(",") if r.strip()]
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    chars_dir, phrases_dir = sys.argv[1], sys.argv[2]
    chars_file = os.path.join(chars_dir, "pinyin.txt")
    phrases_file = os.path.join(phrases_dir, "pinyin.txt")
    chars_version = version(chars_file)
    phrases_version = version(phrases_file)

    chars = {}
    for c, readings in code_chars(chars_file).items():
        rs = []
        for r in readings:
            t = toneless(r)
            if t and t not in rs:
                rs.append(t)
        if rs:
            chars[c] = rs
    pinlu = set(code_chars(os.path.join(chars_dir, "kHanyuPinlu.txt")))
    common = set(code_chars(os.path.join(chars_dir, "kMandarin_8105.txt")))
    syllables = {r for rs in chars.values() for r in rs}

    phrases = []
    seen = set()
    skipped = 0
    with open(phrases_file, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or ":" not in line:
                continue
            text, readings = line.split(":", 1)
            text = text.strip()
            sy = [toneless(r) for r in readings.split()]
            if (
                len(text) < 2
                or len(sy) != len(text)
                or any(s not in syllables for s in sy)
                or any(c not in chars for c in text)
                or " " in text
            ):
                skipped += 1
                continue
            if (text, tuple(sy)) in seen:
                continue
            seen.add((text, tuple(sy)))
            phrases.append((text, sy))

    used = collections.Counter()
    for text, _ in phrases:
        for c in set(text):
            used[c] += 1

    def tier(c):
        if c in common:
            return 0 if c in pinlu else 1
        return 2 if c in pinlu else 3

    order = sorted(chars, key=lambda c: (tier(c), -used[c], ord(c)))
    ranked = sorted(
        enumerate(phrases),
        key=lambda p: (-sum(math.log1p(used[c]) for c in p[1][0]) / len(p[1][0]), p[0]),
    )

    text = io.StringIO()
    text.write("# Runo pinyin data, generated by scripts/pinyin-data.py; do not edit.\n")
    text.write(f"# pinyin-data v{chars_version} (pinyin.txt), MIT, see LICENSE-pinyin-data\n")
    text.write(
        f"# phrase-pinyin-data v{phrases_version} (pinyin.txt), MIT, see LICENSE-phrase-pinyin-data\n"
    )
    text.write("@chars\n")
    last = 0
    for c in order:
        while tier(c) != last:
            text.write("-\n")
            last += 1
        text.write(c + ",".join(chars[c]) + "\n")
    text.write("@phrases\n")
    for _, (p, sy) in ranked:
        text.write(p + " " + " ".join(sy) + "\n")

    os.makedirs(OUT, exist_ok=True)
    raw = text.getvalue().encode("utf-8")
    with open(os.path.join(OUT, "pinyin.txt.gz"), "wb") as f:
        with gzip.GzipFile(filename="", mode="wb", fileobj=f, compresslevel=9, mtime=0) as g:
            g.write(raw)
    for name, src, ver, url in [
        ("LICENSE-pinyin-data", chars_dir, chars_version, "https://github.com/mozillazg/pinyin-data"),
        (
            "LICENSE-phrase-pinyin-data",
            phrases_dir,
            phrases_version,
            "https://github.com/mozillazg/phrase-pinyin-data",
        ),
    ]:
        with open(os.path.join(src, "LICENSE"), encoding="utf-8") as f:
            license_text = f.read()
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
            f.write(f"Source: {url} (tag v{ver})\n\n{license_text}")
    print(
        f"{len(order)} characters, {len(phrases)} phrases ({skipped} skipped), "
        f"{len(raw)} bytes before gzip",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
